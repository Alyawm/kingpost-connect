//! Desktop shell. Wires the Tauri runtime, plugins and the command handlers that the
//! interface calls through `apps/desktop/src/lib/ipc.ts`.

mod commands;

use commands::{
    analysis, cache, clash, compare, diagnostics, drawings, licence, model, notes, project,
    quantity, review, sync, views,
};

pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        .plugin(tauri_plugin_process::init())
        .manage(commands::AppState::from_environment())
        .invoke_handler(tauri::generate_handler![
            project::app_info,
            project::project_is_project,
            project::project_create,
            project::project_open,
            project::project_sample,
            model::project_add_files,
            model::ifc_grids,
            project::project_close,
            project::project_current,
            model::project_files,
            model::import_ifc,
            model::read_project_file,
            model::revision_info,
            model::revision_elements,
            model::element_details,
            model::search_elements,
            views::views_list,
            views::view_save,
            views::view_update,
            notes::notes_list,
            notes::note_add,
            notes::note_update,
            notes::note_delete,
            notes::element_links,
            notes::element_link_add,
            notes::element_link_delete,
            notes::link_open,
            notes::image_save,
            sync::sync_status,
            sync::sync_set_folder,
            sync::sync_set_auto,
            sync::sync_now,
            sync::sync_retry,
            sync::sync_shared_projects,
            sync::sync_join,
            sync::sync_use_server,
            sync::sync_stop,
            sync::sync_server_info,
            sync::sync_server_login,
            sync::sync_server_register,
            sync::sync_server_logout,
            sync::sync_server_accounts,
            sync::sync_server_projects,
            sync::sync_join_server,
            sync::sync_members,
            sync::sync_invite,
            sync::sync_remove_member,
            views::view_set_default,
            views::view_rename,
            views::view_delete,
            review::issues_list,
            review::issue_details,
            review::issue_create,
            review::issue_update,
            review::issue_set_elements,
            review::issue_delete,
            review::comment_add,
            review::viewpoint_add,
            review::viewpoint_snapshot,
            review::viewpoint_delete,
            review::status_list,
            review::status_set,
            review::status_clear,
            review::bcf_export,
            review::bcf_import,
            compare::diff_revisions,
            compare::diff_export_csv,
            analysis::analysis_import,
            analysis::analysis_models,
            analysis::analysis_model,
            analysis::analysis_match,
            analysis::analysis_link_set,
            analysis::analysis_link_override,
            drawings::drawing_import,
            drawings::sheets_register,
            drawings::sheets_list,
            drawings::sheet_thumbnail,
            drawings::sheet_update,
            drawings::sheets_search,
            drawings::sheet_links,
            drawings::element_sheet_links,
            drawings::sheet_link_create,
            drawings::sheet_link_delete,
            drawings::sheet_markups,
            drawings::sheet_markup_add,
            drawings::sheet_markup_delete,
            clash::clash_tests,
            clash::clash_test_create,
            clash::clash_test_delete,
            clash::clash_run_record,
            clash::clash_list,
            clash::clash_set_status,
            diagnostics::log_append,
            diagnostics::diagnostics_bundle,
            licence::licence_status,
            licence::licence_install,
            licence::licence_remove,
            cache::geometry_cache_read,
            cache::geometry_cache_write,
            cache::geometry_cache_clear,
            quantity::schedule_presets,
            quantity::schedule_save,
            quantity::schedule_delete,
            quantity::schedule_evaluate,
            quantity::schedule_export,
            quantity::property_catalogue,
            quantity::geometry_quantity_count,
            quantity::geometry_quantities_save,
            quantity::densities,
            quantity::density_set,
            quantity::density_remove,
        ])
        .run(tauri::generate_context!())
        .expect("failed to start KingPost Connect");
}
